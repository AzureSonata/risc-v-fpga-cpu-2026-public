#!/usr/bin/env python3
"""Emit a checked-in C header from the pinned TFLM frontend parameter blob."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", type=Path, default=Path("verification/kws/k2/frontend/params.bin"))
    ap.add_argument("--output", type=Path, default=Path("firmware/kws/include/kws_frontend_params.h"))
    args = ap.parse_args()

    raw = args.input.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "// Generated by tools/kws/emit_frontend_params.py; do not edit.",
        f"// Source: {args.input.as_posix()} ({len(raw)} bytes, sha256 {digest}).",
        "#ifndef KWS_FRONTEND_PARAMS_H_",
        "#define KWS_FRONTEND_PARAMS_H_",
        "#include <stdint.h>",
        f"#define KWS_FRONTEND_PARAMS_BYTES {len(raw)}u",
        "static const uint8_t kws_frontend_params[KWS_FRONTEND_PARAMS_BYTES] = {",
    ]
    for start in range(0, len(raw), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in raw[start:start + 16]) + ",")
    lines.extend(["};", "#endif  // KWS_FRONTEND_PARAMS_H_", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"PASS: emitted {args.output} ({len(raw)} bytes, sha256 {digest})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
