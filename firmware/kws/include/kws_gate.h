/* KWS GATE -- decision layer: threshold, N-of-M, hysteresis, quadratic rejector.
 *
 * Status: REFERENCE IMPLEMENTATION, integer only. No float, no libm, no 64-bit math,
 * so the same translation unit compiles for the host test and for RV32IM firmware.
 *
 * Why this file exists
 * --------------------
 * The decision layer used to live only in `tools/kws/k2_oov_stream_eval.py` (class
 * EventLayer) -- `grep -rn 'n_of_m\|release_int8' --include=*.c --include=*.sv` over the
 * repo returned nothing outside tools/. That meant every FA/h number in the K2/K3 evidence
 * described a rule that no firmware implemented, and any change to it was unverifiable on
 * device. This is that rule, transcribed.
 *
 * The chain, per 200 ms window, on the four int8 output codes the FC+softmax already
 * produce (q = [silence, unknown, yes, no], p(yes) = (q_yes + 128) / 256):
 *
 *   1. theta gate      q_yes >= KWS_GATE_YES_THETA
 *   2. rejector        s = c0 + sum_{k=1..9} c_k * t_k  ;  accept only if (s >> Q) >= tau
 *                      t = ((q_yes - q_sil) >> S, (q_yes - q_unk) >> S, (q_yes - q_no) >> S)
 *                      and the 9 terms are t0,t1,t2,t0^2,t1^2,t2^2,t0t1,t0t2,t1t2
 *   3. N-of-M          M consecutive accepted windows fire one alarm
 *   4. hysteresis      after an alarm the detector re-arms only when q_yes < release,
 *                      so one activation yields exactly one alarm
 *
 * Why the rejector is a quadratic on three differences and not a margin: K2-10b measured
 * the yes-vs-rest margin at AUC 0.552 on real negatives (i.e. no better than guessing)
 * while this 9-term form reached 0.891 on the same four numbers.
 *
 * Overflow is bounded by construction, not by hope: with |t| <= 16 the largest |term| is
 * 256, and the generator only emits coefficient sets where max|c| * 256 * 9 < 2^31, so the
 * int32 accumulator cannot wrap. `kws_gate_score` additionally saturates and reports it.
 */
#ifndef KWS_GATE_H
#define KWS_GATE_H

#include <stdint.h>

#include "kws_gate_coeffs.h"     /* GENERATED by tools/kws/k3_gen_gate_firmware.py */

#define KWS_GATE_CLASSES 4
#define KWS_GATE_SILENCE 0
#define KWS_GATE_UNKNOWN 1
#define KWS_GATE_YES     2
#define KWS_GATE_NO      3

#define KWS_GATE_N_TERMS 9

typedef struct {
  int32_t c[KWS_GATE_N_TERMS + 1];   /* c[0] = bias, c[1..9] = term coefficients */
  int32_t q_shift;                   /* >> q_shift undoes the fixed-point scale */
  int32_t tau;                       /* reject when score < tau */
  int32_t theta;                     /* gate: q_yes >= theta */
  int32_t release;                   /* hysteresis: re-arm when q_yes < release */
  int32_t n_of_m;                    /* consecutive accepted windows per alarm */
} kws_gate_cfg_t;

typedef struct {
  int32_t run;                       /* length of the current accepted run */
  int32_t armed;                     /* 1 = able to fire */
} kws_gate_state_t;

/* The frozen operating point selected on the MUSAN dev bucket. */
const kws_gate_cfg_t *kws_gate_default_cfg(void);

void kws_gate_reset(kws_gate_state_t *st);

/* Integer rejector score, exactly (s >> q_shift) as the firmware computes it.
 * Returns 0 on success, -1 on null argument. *out receives the shifted score.
 * *sat (may be null) is set to 1 if the int32 accumulator would have overflowed,
 * in which case *out is clamped -- an overflow must never be silent. */
int kws_gate_score(const kws_gate_cfg_t *cfg, const int8_t q[KWS_GATE_CLASSES],
                   int32_t *out, int *sat);

/* One-window decision: theta AND rejector. Returns 1 accept, 0 reject, -1 bad args. */
int kws_gate_accept(const kws_gate_cfg_t *cfg, const int8_t q[KWS_GATE_CLASSES]);

/* Feed one window. Returns 1 when this window completes an alarm, else 0, -1 on bad args.
 * `t` is unused for the decision (kept out on purpose: no float, no time base here). */
int kws_gate_feed(const kws_gate_cfg_t *cfg, kws_gate_state_t *st,
                  const int8_t q[KWS_GATE_CLASSES]);

#endif /* KWS_GATE_H */
